// Builds js/soe-candidate-cases.js — the password-encrypted long-case candidate
// sheets shown on candidate.html.
//
// Content comes from the <section id="candidate"> of soe-packs/station1-mockN.html
// (same source as the printed candidate sheets). Images are inlined as data URIs so
// they are encrypted too. Each case is AES-GCM encrypted with a key derived from its
// password (PBKDF2-SHA256), so nothing is readable from page source without it.
//
// Usage:
//   node scripts/build-candidate-cases.mjs --mock1 <password> --mock2 <password> --practice <password>
//
// Pass only the cases you want to (re)encrypt: any case without a password keeps its
// existing encrypted entry from js/soe-candidate-cases.js, so adding or editing one case
// doesn't need the other cases' passwords.
//
// Passwords are never written to disk. Re-run with new passwords to change them.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PACKS = path.join(ROOT, 'soe-packs');
const ITERATIONS = 250000;

// key = 'mock' + the ?mock= value on candidate.html; arg = the command-line flag.
const MOCKS = [
  { key: 'mock1', arg: 'mock1', file: 'station1-mock1.html', title: 'Mock Exam 1 — Long case' },
  { key: 'mock2', arg: 'mock2', file: 'station1-mock2.html', title: 'Mock Exam 2 — Long case' },
  { key: 'mockpractice', arg: 'practice', file: 'station1-practice.html', title: 'Practice session — Long case 1' }
];

function arg(name){
  const i = process.argv.indexOf('--' + name);
  return i > -1 ? process.argv[i + 1] : null;
}

function extractBalancedDiv(html, start){
  let depth = 1, i = start;
  while (depth > 0){
    const o = html.indexOf('<div', i), c = html.indexOf('</div>', i);
    if (c === -1) throw new Error('unbalanced div');
    if (o !== -1 && o < c){ depth++; i = o + 4; } else { depth--; i = c + 6; }
  }
  return { content: html.slice(start, i - 6), end: i };
}

function candidateHtml(file){
  const html = fs.readFileSync(path.join(PACKS, file), 'utf8');
  const s = html.indexOf('<section id="candidate">');
  const e = html.indexOf('</section>', s);
  const sec = html.slice(s, e);

  const ulS = sec.indexOf('<ul>', sec.indexOf('Instructions to candidate'));
  const instructions = sec.slice(ulS, sec.indexOf('</ul>', ulS) + 5);

  const caseTag = sec.indexOf('<div class="case"');
  const { content: caseInner, end: caseEnd } = extractBalancedDiv(sec, sec.indexOf('>', caseTag) + 1);
  const caseBody = caseInner.replace(/^\s*<p class="eyebrow"[\s\S]*?<\/p>\s*/, '');

  let images = '';
  const mriIdx = sec.indexOf('<div class="mri">', caseEnd);
  if (mriIdx !== -1){
    const { content } = extractBalancedDiv(sec, mriIdx + '<div class="mri">'.length);
    images = '<div class="mri">' + content.replace(/src="(img\/[^"]+)"/g, (_, rel) => {
      const buf = fs.readFileSync(path.join(PACKS, rel));
      return 'src="data:image/png;base64,' + buf.toString('base64') + '"';
    }) + '</div>';
  }

  return '<section class="instr"><p class="label">Instructions to candidate</p>' + instructions + '</section>' +
         '<section class="case"><p class="label">Case history</p>' + caseBody + images + '</section>';
}

async function encrypt(plaintext, password){
  const enc = new TextEncoder();
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const baseKey = await crypto.subtle.importKey('raw', enc.encode(password), 'PBKDF2', false, ['deriveKey']);
  const key = await crypto.subtle.deriveKey(
    { name: 'PBKDF2', salt, iterations: ITERATIONS, hash: 'SHA-256' },
    baseKey, { name: 'AES-GCM', length: 256 }, false, ['encrypt']);
  const ct = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, enc.encode(plaintext));
  const b64 = u => Buffer.from(u).toString('base64');
  return { salt: b64(salt), iv: b64(iv), iterations: ITERATIONS, data: b64(new Uint8Array(ct)) };
}

const target = path.join(ROOT, 'js', 'soe-candidate-cases.js');

function existingCases(){
  if (!fs.existsSync(target)) return {};
  const src = fs.readFileSync(target, 'utf8');
  const m = src.match(/window\.SOE_CANDIDATE_CASES = (\{[\s\S]*\});\s*$/);
  return m ? JSON.parse(m[1]) : {};
}

const existing = existingCases();
const out = {};
for (const m of MOCKS){
  const pw = arg(m.arg);
  if (pw){
    out[m.key] = { title: m.title, ...(await encrypt(candidateHtml(m.file), pw)) };
    console.log(m.key, 'encrypted');
  } else if (existing[m.key]){
    out[m.key] = existing[m.key];
    console.log(m.key, 'kept (no --' + m.arg + ' given)');
  } else {
    throw new Error('Missing --' + m.arg + ' <password> (no existing entry to keep)');
  }
}

fs.writeFileSync(target,
  '// Generated by scripts/build-candidate-cases.mjs — encrypted long-case candidate sheets.\n' +
  'window.SOE_CANDIDATE_CASES = ' + JSON.stringify(out) + ';\n');
console.log('wrote', path.relative(ROOT, target));
