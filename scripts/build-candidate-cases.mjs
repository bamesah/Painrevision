// Builds js/soe-candidate-cases.js — the long-case candidate sheets shown on candidate.html.
//
// Content comes from the <section id="candidate"> of soe-packs/station1-mockN.html
// (same source as the printed candidate sheets). Images are inlined as data URIs.
// Cases are not password protected: the 10-minute reading timer starts as soon as a
// candidate opens candidate.html?mock=N. The HTML is base64-encoded only so it isn't
// readable at a glance in the page source.
//
// Usage:
//   node scripts/build-candidate-cases.mjs

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PACKS = path.join(ROOT, 'soe-packs');

// key = 'mock' + the ?mock= value on candidate.html.
const MOCKS = [
  { key: 'mock1', file: 'station1-mock1.html', title: 'Mock Exam 1 — Long case' },
  { key: 'mock2', file: 'station1-mock2.html', title: 'Mock Exam 2 — Long case' }
];


function extractBalancedDiv(html, start){
  let depth = 1, i = start;
  while (depth > 0){
    const o = html.indexOf('<div', i), c = html.indexOf('</div>', i);
    if (c === -1) throw new Error('unbalanced div');
    if (o !== -1 && o < c){ depth++; i = o + 4; } else { depth--; i = c + 6; }
  }
  return { content: html.slice(start, i - 6), end: i };
}

function candidateHtml(file){
  const html = fs.readFileSync(path.join(PACKS, file), 'utf8');
  const s = html.indexOf('<section id="candidate">');
  const e = html.indexOf('</section>', s);
  const sec = html.slice(s, e);

  const ulS = sec.indexOf('<ul>', sec.indexOf('Instructions to candidate'));
  const instructions = sec.slice(ulS, sec.indexOf('</ul>', ulS) + 5);

  const caseTag = sec.indexOf('<div class="case"');
  const { content: caseInner, end: caseEnd } = extractBalancedDiv(sec, sec.indexOf('>', caseTag) + 1);
  const caseBody = caseInner.replace(/^\s*<p class="eyebrow"[\s\S]*?<\/p>\s*/, '');

  let images = '';
  const mriIdx = sec.indexOf('<div class="mri">', caseEnd);
  if (mriIdx !== -1){
    const { content } = extractBalancedDiv(sec, mriIdx + '<div class="mri">'.length);
    images = '<div class="mri">' + content.replace(/src="(img\/[^"]+)"/g, (_, rel) => {
      const buf = fs.readFileSync(path.join(PACKS, rel));
      return 'src="data:image/png;base64,' + buf.toString('base64') + '"';
    }) + '</div>';
  }

  return '<section class="instr"><p class="label">Instructions to candidate</p>' + instructions + '</section>' +
         '<section class="case"><p class="label">Case history</p>' + caseBody + images + '</section>';
}

const target = path.join(ROOT, 'js', 'soe-candidate-cases.js');

const out = {};
for (const m of MOCKS){
  out[m.key] = { title: m.title, html: Buffer.from(candidateHtml(m.file), 'utf8').toString('base64') };
  console.log(m.key, 'built');
}

fs.writeFileSync(target,
  '// Generated by scripts/build-candidate-cases.mjs — long-case candidate sheets.\n' +
  'window.SOE_CANDIDATE_CASES = ' + JSON.stringify(out) + ';\n');
console.log('wrote', path.relative(ROOT, target));
